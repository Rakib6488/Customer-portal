// Standard categories and mapping
export function parsePastedRoster(yearNum = 2026, monthNum = 6, fallbackGenerator: (yr: number, mn: number, s: number) => RosterDay[]): RosterDay[] {
  // We only parse for July 2026 (year = 2026, monthNum = 6)
  if (yearNum !== 2026 || monthNum !== 6) {
    return fallbackGenerator(yearNum, monthNum, 0);
  }

  const numDays = new Date(yearNum, monthNum + 1, 0).getDate();
  const daysOfWeek = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];

  // Initialize roster structure
  const roster: RosterDay[] = [];
  for (let d = 1; d <= numDays; d++) {
    const dateStr = `${yearNum}-${String(monthNum + 1).padStart(2, '0')}-${String(d).padStart(2, '0')}`;
    const dateObj = new Date(yearNum, monthNum, d);
    const dayOfWeekName = daysOfWeek[dateObj.getDay()];

    roster.push({
      id: `roster-${dateStr}`,
      date: dateStr,
      dayOfWeek: dayOfWeekName,
      shifts: {
        morning: [],
        standardDay: [],
        lateDay: [],
        afternoon: [],
        evening: [],
        night: [],
        off: []
      },
      notes: 'Pasted official July 2026 roster loaded.',
      isAutoGenerated: false
    });
  }

  const lines = RAW_PASTED_ROSTER.trim().split('\n');
  if (lines.length < 3) {
    return fallbackGenerator(yearNum, monthNum, 0);
  }

  // Row 0 is the dates: e.g. "1-Jul-26", "2-Jul-26", ...
  const dateHeaders = lines[0].split('\t').map(d => d.trim());
  
  // Let's find index of each date e.g. "1-Jul-26" maps to day 1, "2-Jul-26" maps to day 2, etc.
  // Note that dateHeaders can be like ["1-Jul-26", "2-Jul-26", ...]
  const dayIndices: { [headerIdx: number]: number } = {};
  for (let i = 0; i < dateHeaders.length; i++) {
    const parts = dateHeaders[i].split('-');
    if (parts.length >= 2) {
      const dayNum = parseInt(parts[0], 10);
      if (!isNaN(dayNum) && dayNum >= 1 && dayNum <= numDays) {
        dayIndices[i] = dayNum;
      }
    }
  }

  // Iterate from line index 2 onwards (ignoring headers)
  for (let r = 2; r < lines.length; r++) {
    const cols = lines[r].split('\t');
    if (cols.length < 3) continue;

    const agentName = cols[0].trim();
    if (!agentName) continue;

    // The shift cells are index 2 onwards
    for (let c = 2; c < cols.length; c++) {
      // Find what day this column index maps to
      // dateHeaders and columns map 1-to-1, wait!
      // Wait, let's verify if row 1 (the Day names Wed, Thu...) has same length
      // Yes, cols[0] is Name, cols[1] is Agent Portal ID.
      // So the date values start at column index 2.
      // E.g. c = 2 corresponds to July 1st, c = 3 to July 2nd...
      // Let's verify with the dateHeaders.
      // The dateHeaders starts with "1-Jul-26", "2-Jul-26", ... which has no "Name" or "Agent Portal ID" at index 0 or 1!
      // Wait, let's look at RAW_PASTED_ROSTER:
      // Row 0: "1-Jul-26	2-Jul-26	3-Jul-26..."
      // Oh! Row 0 starts directly with the dates! It does not have "Name" or "Agent Portal ID" at columns 0 and 1!
      // Let's verify: Row 0 has 26 tab-separated values.
      // Row 1 (Name	Agent Portal ID	Wed	Thu...): Column 0 is Name, Column 1 is Agent Portal ID, Column 2 is Wed, Column 3 is Thu...
      // So column 2 maps to date index 0 ("1-Jul-26"), column 3 maps to date index 1 ("2-Jul-26"), and so on!
      // Let's verify this mapping.
      // Yes!
      // Date headers: Index 0 is "1-Jul-26" (July 1st).
      // Row 1 columns: Index 0 is Name, Index 1 is Agent Portal ID, Index 2 is Wed (which is 1-Jul-26).
      // So date index `headerIdx` matches column `c = headerIdx + 2`!
      const dateHeaderIdx = c - 2;
      const dayNum = dayIndices[dateHeaderIdx];
      if (dayNum === undefined) continue;

      const rawShiftVal = cols[c]?.trim();
      if (!rawShiftVal) {
        // Empty/No shift maps to off
        roster[dayNum - 1].shifts.off.push(agentName);
        continue;
      }

      const valLower = rawShiftVal.toLowerCase();

      if (valLower.includes('off') || valLower.includes('eid') || valLower === '') {
        roster[dayNum - 1].shifts.off.push(agentName);
      } else if (valLower.startsWith('7:') || valLower.startsWith('7 ')) {
        roster[dayNum - 1].shifts.morning.push(agentName);
      } else if (valLower.startsWith('8:') || valLower.startsWith('8 ')) {
        roster[dayNum - 1].shifts.standardDay.push(agentName);
      } else if (valLower.startsWith('10:') || valLower.startsWith('10 ')) {
        roster[dayNum - 1].shifts.lateDay.push(agentName);
      } else if (valLower.startsWith('2:') || valLower.startsWith('2 ')) {
        roster[dayNum - 1].shifts.afternoon.push(agentName);
      } else if (valLower.startsWith('5:') || valLower.startsWith('5 ')) {
        roster[dayNum - 1].shifts.evening.push(agentName);
      } else if (valLower.startsWith('11:') || valLower.startsWith('11 ')) {
        roster[dayNum - 1].shifts.night.push(agentName);
      } else {
        // Fallback for custom or half day items
        if (valLower.includes('10 am') || valLower.includes('10:00')) {
          roster[dayNum - 1].shifts.lateDay.push(agentName);
        } else if (valLower.includes('5:00') || valLower.includes('5 pm')) {
          roster[dayNum - 1].shifts.evening.push(agentName);
        } else if (valLower.includes('8:00') || valLower.includes('8 am')) {
          roster[dayNum - 1].shifts.standardDay.push(agentName);
        } else if (valLower.includes('7:00') || valLower.includes('7 am')) {
          roster[dayNum - 1].shifts.morning.push(agentName);
        } else if (valLower.includes('2:00') || valLower.includes('2 pm')) {
          roster[dayNum - 1].shifts.afternoon.push(agentName);
        } else if (valLower.includes('11:00') || valLower.includes('11 pm')) {
          roster[dayNum - 1].shifts.night.push(agentName);
        } else {
          // Default fallback to off
          roster[dayNum - 1].shifts.off.push(agentName);
        }
      }
    }
  }

  // For any days that are beyond the pasted columns (e.g., July 27th to July 31st),
  // generate a beautiful auto-roster based on the default seed so there are no empty gaps!
  const fallbackDays = fallbackGenerator(yearNum, monthNum, 0);
  for (let d = 1; d <= numDays; d++) {
    const isPastedDay = Object.keys(dayIndices).some(k => dayIndices[Number(k)] === d);
    if (!isPastedDay) {
      // Use fallback days for days 27-31
      roster[d - 1] = fallbackDays[d - 1];
    }
  }

  return roster;
}
